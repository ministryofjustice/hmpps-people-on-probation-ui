import crypto from 'crypto'
import express, { Router, Request, Response, NextFunction } from 'express'
import helmet from 'helmet'
import config, { isChatbotVoiceEnabled } from '../config'

export default function setUpWebSecurity(): Router {
  const router = express.Router()

  const { feedbackBanner } = config
  const isFeedbackPage = (req: Request) => req.path === '/feedback'
  const isWelcomePage = (req: Request) => req.path === '/welcome'

  // Secure code best practice - see:
  // 1. https://expressjs.com/en/advanced/best-practice-security.html,
  // 2. https://www.npmjs.com/package/helmet
  router.use((_req: Request, res: Response, next: NextFunction) => {
    res.locals.cspNonce = crypto.randomBytes(16).toString('hex')
    next()
  })
  router.use(
    helmet({
      contentSecurityPolicy: {
        directives: {
          defaultSrc: ["'self'"],
          // This nonce allows us to use scripts with the use of the `cspNonce` local, e.g (in a Nunjucks template):
          // <script nonce="{{ cspNonce }}">
          // or
          // <link href="http://example.com/" rel="stylesheet" nonce="{{ cspNonce }}">
          // This ensures only scripts we trust are loaded, and not anything injected into the
          // page by an attacker.
          scriptSrc: [
            "'self'",
            ...(feedbackBanner.enabled ? ['https://embed.smartsurvey.io'] : []),
            (_req: Request, res: Response) => `'nonce-${res.locals.cspNonce}'`,
          ],
          // 'unsafe-inline' is only needed for SmartSurvey popup which injects inline styles dynamically.
          styleSrc: ["'self'", ...(feedbackBanner.enabled ? ["'unsafe-inline'"] : []), 'https://fonts.googleapis.com'],
          fontSrc: ["'self'", 'https://fonts.gstatic.com'],
          imgSrc: ["'self'", 'data:', ...(feedbackBanner.enabled ? ['https://embed.smartsurvey.io'] : [])],
          // Wildcarded on subdomain since presigned S3 URLs (Documents feature) carry a
          // bucket-specific hostname (virtual-hosted-style, generated by the terraform module)
          // that isn't known/fixed in advance - only the region is. 'blob:' is needed for the
          // admin upload preview, which renders the locally-selected file via a blob: URL
          // (URL.createObjectURL) before anything is uploaded.
          connectSrc: ["'self'", 'https://www.smartsurvey.co.uk', 'https://*.s3.eu-west-2.amazonaws.com', 'blob:'],
          frameSrc: ['https://www.smartsurvey.co.uk', 'https://www.veed.io'],
          // Spoken chatbot replies are fetched from our own /api/chatbot/voice/speak
          // and played from a blob: URL (the audio never has a fetchable URL of
          // its own, so <audio src> can't point at 'self' directly).
          mediaSrc: ["'self'", 'blob:'],
          formAction: [`'self' ${config.oneLogin.issuerUrl}`],
          ...(config.production ? {} : { upgradeInsecureRequests: null }),
        },
      },
      // COEP is applied below so it can be relaxed only where SmartSurvey is embedded.
      crossOriginEmbedderPolicy: false,
      // helmet defaults to 'no-referrer', which strips document.referrer on
      // every navigation, including same-origin ones — that's what the
      // analytics referrerPath property (assets/js/lib/analytics/events.ts)
      // relies on to answer "what page did this page view come from".
      // 'same-origin' keeps that working while still sending nothing at all
      // to external sites when a user navigates away from this app.
      referrerPolicy: { policy: 'same-origin' },
    }),
  )
  // helmet doesn't set Permissions-Policy. The only thing on this site that
  // ever asks for the microphone is the chatbot's voice input, and only from
  // our own origin — so allow exactly that when voice is on, and say so
  // explicitly when it's off rather than leaving the browser default.
  router.use((_req: Request, res: Response, next: NextFunction) => {
    res.setHeader('Permissions-Policy', isChatbotVoiceEnabled() ? 'microphone=(self)' : 'microphone=()')
    next()
  })
  router.use((req: Request, res: Response, next: NextFunction) => {
    if (!feedbackBanner.enabled && !isFeedbackPage(req) && !isWelcomePage(req)) {
      res.setHeader('Cross-Origin-Embedder-Policy', 'require-corp')
    }
    next()
  })
  return router
}
